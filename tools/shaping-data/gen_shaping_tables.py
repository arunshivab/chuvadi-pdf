#!/usr/bin/env python3
"""Generates src/Chuvadi.Pdf.Text.Shaping/Unicode/UnicodeTables.g.cs.

Input: ucd.tsv written by tools/shaping-data/hb_ucd_dump.cc (built against a
HarfBuzz checkout), so the tables match the Unicode data HarfBuzz shapes
with. Usage:

    python tools/shaping-data/gen_shaping_tables.py <ucd.tsv>

Each table is a base64 blob of fixed-size big-endian records:
  GeneralCategory   runs: start(3) value(1)
  CombiningClass    runs: start(3) value(1)   (HarfBuzz modified classes)
  Indic             runs: start(3) category(1) position(1)
  Decompositions    rows: ab(3) a(3) b(3) recomposes(1)  (Hangul excluded)
"""

import base64
import os
import sys

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'Chuvadi.Pdf.Text.Shaping',
                   'Unicode', 'UnicodeTables.g.cs')


def runs(values):
    out = []
    prev = None
    for i, v in enumerate(values):
        if v != prev:
            out.append((i, v))
            prev = v
    return out


def b3(v):
    return bytes([(v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF])


def blob(name, data):
    text = base64.b64encode(data).decode('ascii')
    lines = [text[i:i + 100] for i in range(0, len(text), 100)]
    body = '\n        + '.join('"%s"' % l for l in lines)
    return '    internal const string %s =\n        %s;\n' % (name, body)


def main():
    rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[1], encoding='ascii')]
    gc = [int(r[1]) for r in rows]
    mcc = [int(r[3]) for r in rows]
    ind = [int(r[8]) for r in rows]

    gc_data = b''.join(b3(s) + bytes([v]) for s, v in runs(gc))
    cc_data = b''.join(b3(s) + bytes([v]) for s, v in runs(mcc))
    ind_data = b''.join(b3(s) + bytes([v & 0xFF, v >> 8]) for s, v in runs(ind))

    dec = []
    for r in rows:
        u = int(r[0], 16)
        if r[6] != '1' or 0xAC00 <= u <= 0xD7A3:
            continue
        dec.append(b3(u) + b3(int(r[4], 16)) + b3(int(r[5], 16)) + bytes([int(r[7])]))
    dec_data = b''.join(dec)

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Copyright 2025 Chuvadi Contributors\n')
        f.write('// SPDX-License-Identifier: Apache-2.0\n')
        f.write('// <auto-generated>\n')
        f.write('// Generated by tools/shaping-data/gen_shaping_tables.py from the Unicode\n')
        f.write('// data of HarfBuzz (see tools/shaping-data/hb_ucd_dump.cc). Do not edit.\n')
        f.write('// </auto-generated>\n\n')
        f.write('namespace Chuvadi.Pdf.Text.Shaping.Unicode;\n\n')
        f.write('/// <summary>Packed Unicode and Indic property tables (base64).</summary>\n')
        f.write('internal static class UnicodeTables\n{\n')
        f.write(blob('GeneralCategory', gc_data))
        f.write('\n')
        f.write(blob('CombiningClass', cc_data))
        f.write('\n')
        f.write(blob('Indic', ind_data))
        f.write('\n')
        f.write(blob('Decompositions', dec_data))
        f.write('}\n')


if __name__ == '__main__':
    main()
