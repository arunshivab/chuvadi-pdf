#!/usr/bin/env python3
"""Generate src/Chuvadi.Pdf.Authoring/LatinGlyphNames.cs (3.33.0, ticket 46).

The /Differences encoding a standard-14 substitute gets (PDF/A-2b and the
embed operation) must name each glyph with an Adobe Glyph List name
(ISO 19005-2 §6.2.11.6). This table gives one AGL name for each Unicode
value a Latin text font's encodings use: Latin-1 and Latin Extended,
spacing modifiers, Greek, general punctuation through mathematical
operators, the lozenge and the Latin ligatures.

Where the AGL has several names for one value, the shortest is taken (then
the first in alphabetical order), so the table never depends on file order.

Source, in the repository (no network access): tools/agl/glyphlist.txt
(AGL 2.0).

Regenerate via:
    python tools/gen_latin_glyph_names.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "Chuvadi.Pdf.Authoring" / "LatinGlyphNames.cs"
RANGES = [(0x0020, 0x024F), (0x02B0, 0x02FF), (0x0370, 0x03FF), (0x2000, 0x22FF), (0x25CA, 0x25CA), (0xFB00, 0xFB06)]

names = {}
for line in (ROOT / "tools" / "agl" / "glyphlist.txt").read_text(encoding="utf-8").splitlines():
    if not line or line.startswith("#"):
        continue
    name, value = line.split(";", 1)
    cps = value.split()
    if len(cps) != 1:
        continue
    cp = int(cps[0], 16)
    if not any(lo <= cp <= hi for lo, hi in RANGES):
        continue
    names.setdefault(cp, []).append(name)

rows = []
for cp in sorted(names):
    best = sorted(names[cp], key=lambda n: (len(n), n))[0]
    rows.append(f"        [0x{cp:04X}] = \"{best}\",")

text = f"""// <auto-generated>
//     One Adobe Glyph List name per Unicode value for the Latin text fonts'
//     encodings (3.33.0, ticket 46). {len(rows)} entries.
//     Do not edit by hand. Regenerate via tools/gen_latin_glyph_names.py.
// </auto-generated>

using System.Collections.Generic;

namespace Chuvadi.Pdf.Authoring;

/// <summary>An Adobe Glyph List name for each Unicode value a Latin text font's encodings use.</summary>
internal static class LatinGlyphNames
{{
    /// <summary>Unicode value to glyph name.</summary>
    internal static readonly IReadOnlyDictionary<int, string> ByUnicode = new Dictionary<int, string>
    {{
{chr(10).join(rows)}
    }};
}}
"""
OUT.write_text(text, encoding="utf-8", newline="\n")
print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} entries")
